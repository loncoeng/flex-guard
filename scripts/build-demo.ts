// Generate docs/index.html, which is what GitHub Pages serves.
//
// What the demo runs is the build output of src, not a version rewritten for
// the page. **Rewritten, it drifts from the real thing** — and a fix that is
// still the old behaviour in the demo is the worst state of the three.
//
//   npm run demo:build    generate it and write it out
//   npm run demo:check    regenerate it and check for a difference (for CI)
//
// The page is static and asks a server for nothing once it is open. The
// checking happens entirely inside the visitor's browser.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const MARKER = "/* __FLEX_GUARD_BUNDLE__ */";

/** The order they are concatenated in: dependency order. */
const MODULES = [
  "spec.js",
  "walk.js",
  "detect.js",
  "rules/schema.js",
  "rules/size.js",
  "rules/render.js",
  "rules/variables.js",
  "index.js",
];

const IMPORT_LINE = /^\s*import\s.*?;\s*$/gm;
const EXPORT_FROM = /^\s*export\s+\{[^}]*\}\s+from\s+[^;]+;\s*$/gm;
const EXPORT_KEYWORD = /^(\s*)export\s+(const|function|class|let|var)\b/gm;

/**
 * Put the build output into one script.
 *
 * No bundler. There are no dependencies and only eight modules, so dropping
 * the import and export lines and joining them in order is enough. Ten lines
 * you can read beats one more tool in the chain.
 */
function bundle(): string {
  const parts = MODULES.map((name) => {
    const source = readFileSync(join(ROOT, "dist", "src", name), "utf8")
      .replace(IMPORT_LINE, "")
      .replace(EXPORT_FROM, "")
      .replace(EXPORT_KEYWORD, "$1$2")
      .trim();
    return `// ---- ${name} ----\n${source}\n`;
  });

  return [
    "// flex-guard's build output, bundled as it is. Not a rewrite for the demo.",
    "// Generated by: npm run demo:build",
    "const FlexGuard = (() => {",
    parts.join("\n"),
    "return { validate, format, looksLikeFlex };",
    "})();",
  ].join("\n");
}

function render(): string {
  // tsc is started from node directly. Going through npx needs a shell, and
  // then this has to be written once per operating system.
  execFileSync(process.execPath, [join(ROOT, "node_modules", "typescript", "bin", "tsc")], {
    cwd: ROOT,
    stdio: "inherit",
  });
  const template = readFileSync(join(HERE, "demo-template.html"), "utf8");
  if (!template.includes(MARKER)) throw new Error("the template has nowhere to insert the bundle");

  const script = bundle();
  // A </script> inside this closes the HTML early. It should never end up in
  // the build output, and if it does, quietly publishing a broken page is the
  // worse outcome.
  if (/<\/script/i.test(script)) throw new Error("the bundle contains </script>");

  return template.replace(MARKER, script);
}

const html = render();
const target = join(ROOT, "docs", "index.html");

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== html) {
    console.error("  docs/index.html does not match src. Run npm run demo:build.");
    process.exit(1);
  }
  console.log("  docs/index.html matches src");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, html, "utf8");
  console.log(`  wrote docs/index.html (${html.length.toLocaleString()} bytes)`);
}
